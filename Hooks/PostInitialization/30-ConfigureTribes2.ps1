#Requires -Modules Logging

# Write GameData/<T2_MOD>/prefs/lancommander.cs, which t2-server loads with -serverprefs. It loads
# the game's own prefs/ServerPrefs.cs (the game re-exports its $Host:: settings there, so edits in
# Overlay/ and in-game changes persist) and then applies the non-empty T2_* settings on top.
#
# Also make sure <mod>/autoexec.cs turns on console.log, which t2-server streams to docker logs.
# setLogMode only takes effect from autoexec.cs, not from the prefs file.

$mod   = if ($Env:T2_MOD) { $Env:T2_MOD } else { 'base' }
$prefs = Join-Path $Env:SERVER_ROOT "GameData/$mod/prefs"

if (-not (Test-Path -Path (Join-Path $Env:SERVER_ROOT "GameData/$mod"))) {
    Write-Log -Level Error "GameData/$mod not found; skipping server configuration"
    return
}

function ConvertTo-TorqueString([string] $Value) {
    '"' + $Value.Replace('\', '\\').Replace('"', '\"') + '"'
}

$settings = [ordered]@{
    'Map'                       = $Env:T2_MAP
    'MissionType'               = $Env:T2_MISSION_TYPE
    'Port'                      = $Env:T2_PORT
    'GameName'                  = $Env:T2_SERVER_NAME
    'Info'                      = $Env:T2_SERVER_INFO
    'MaxPlayers'                = $Env:T2_MAX_PLAYERS
    'Password'                  = $Env:T2_PASSWORD
    'AdminPassword'             = $Env:T2_ADMIN_PASSWORD
    'ClassicSuperAdminPassword' = $Env:T2_SUPER_ADMIN_PASSWORD
    'TimeLimit'                 = $Env:T2_TIME_LIMIT
    'BotsEnabled'               = $Env:T2_BOTS_ENABLED
    'BotCount'                  = $Env:T2_BOT_COUNT
    'TeamDamageOn'              = $Env:T2_TEAM_DAMAGE
}

$lines = @(
    '// Generated by LANCommander on every start from the T2_* environment variables.'
    '// Edit prefs/ServerPrefs.cs instead; settings with a non-empty T2_* variable win.'
    ''
    'exec("prefs/ServerPrefs.cs", true, true);'
    ''
)

foreach ($s in $settings.GetEnumerator()) {
    if (-not $s.Value) { continue }
    $lines += "`$Host::$($s.Key) = $(ConvertTo-TorqueString $s.Value);"
}

$lines += '$Host::Dedicated = 1;'

New-Item -ItemType Directory -Path $prefs -Force | Out-Null
$file = Join-Path $prefs 'lancommander.cs'
[System.IO.File]::WriteAllText($file, ($lines -join "`r`n") + "`r`n")
chown -R "$($Env:UID):$($Env:GID)" $prefs

Write-Log "Wrote T2_* settings to GameData/$mod/prefs/lancommander.cs"

# Mode 1 flushes console.log after every line. Keep any existing autoexec.cs and add the line once.
$autoexec = Join-Path $Env:SERVER_ROOT "GameData/$mod/autoexec.cs"
$logLine  = 'setLogMode(1); // LANCommander: console.log is streamed to docker logs'

if (-not (Test-Path -Path $autoexec) -or -not (Select-String -Path $autoexec -SimpleMatch 'LANCommander:' -Quiet)) {
    Add-Content -Path $autoexec -Value "`r`n$logLine`r`n" -NoNewline
    chown "$($Env:UID):$($Env:GID)" $autoexec
    Write-Log "Enabled console.log in GameData/$mod/autoexec.cs"
}
